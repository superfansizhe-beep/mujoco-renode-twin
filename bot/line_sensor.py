"""Eight-channel optical line array and firmware-facing observations.

Black detection, GPIO polarity, indicator LEDs and illumination are
separate signals. Optical parameters are simulation assumptions until
measured; the controller only receives the digital mask.
"""
from dataclasses import dataclass
from cad_modeling import layout
from .sensors import LINE_PITCH, N_LINE_SENSORS

MASK = (1 << N_LINE_SENSORS) - 1
ACTIVE_LOW = True
FOOTPRINT_RADIUS_M = 0.0015       # assumption, not a measured optical spot
BLACK_ON, BLACK_OFF = 0.55, 0.45
MIN_RANGE_M, MAX_RANGE_M = 0.005, 0.060
HOLD_S, FILTER_S = 0.080, 0.020
ERROR_SLEW_M_S, ERROR_CAP_M = 0.35, 0.080
END_CONFIRM_S, END_PROGRESS_MIN = 0.300, 0.75
BAR_AHEAD_M = -layout.LINE_BAR_Y / 1000.0
SENSOR_XS = tuple((i - (N_LINE_SENSORS - 1) / 2) * LINE_PITCH
                  for i in range(N_LINE_SENSORS))
_DISK = tuple((x / 2, y / 2) for x in range(-2, 3)
              for y in range(-2, 3) if x * x + y * y <= 4)


def firmware_config() -> str:
    def f(v):
        value = f"{v:.9g}"
        return value + ("f" if any(c in value for c in ".eE") else ".0f")
    values = {"COUNT": str(N_LINE_SENSORS), "ACTIVE_LOW": str(int(ACTIVE_LOW)),
              "PITCH": f(LINE_PITCH), "BAR_AHEAD": f(BAR_AHEAD_M),
              "HOLD_S": f(HOLD_S), "FILTER_S": f(FILTER_S),
              "ERROR_SLEW": f(ERROR_SLEW_M_S), "ERROR_CAP": f(ERROR_CAP_M),
              "END_CONFIRM_S": f(END_CONFIRM_S), "END_PROGRESS_MIN": f(END_PROGRESS_MIN)}
    return ("/* Generated by python -m race.fwconfig from bot.line_sensor. */\n"
            "#ifndef LINE_CONFIG_H\n#define LINE_CONFIG_H\n" +
            "".join(f"#define LINE_CFG_{k} {v}\n" for k, v in values.items()) +
            "#endif\n")


@dataclass(frozen=True)
class Observation:
    bits: int
    count: int
    groups: int
    status: str
    error_m: float | None
    bar_centered: bool

    @property
    def valid(self) -> bool:
        return self.status == "track"

    def payload(self) -> dict:
        return {"bits": self.bits, "count": self.count, "groups": self.groups,
                "status": self.status, "valid": self.valid,
                "error_mm": (round(self.error_m * 1000, 2)
                             if self.error_m is not None else None),
                "bar_centered": self.bar_centered}


def observe(bits: int) -> Observation:
    bits &= MASK
    active = [i for i in range(N_LINE_SENSORS) if bits >> i & 1]
    groups = sum(i == 0 or not (bits >> (i - 1) & 1) for i in active)
    status = ("lost" if not active else "split" if groups != 1
              else "wide" if len(active) > 4 else "track")
    error = sum(SENSOR_XS[i] for i in active) / len(active) \
        if status == "track" else None
    # ARRAY center, never a claim about chassis alignment or heading.
    centered = error is not None and abs(error) < LINE_PITCH * 0.25
    return Observation(bits, len(active), groups, status, error, centered)


class LineEndpoint:
    """Confirm a clean-to-white exit; a brief dropout cannot advance a leg."""
    def __init__(self) -> None:
        self.reset()

    def reset(self) -> None:
        self.had_clean = self.candidate = False
        self.white_cycles = 0

    def update(self, observation: Observation, taped: bool,
               late_possible: bool, dt: float) -> bool:
        if not taped or observation.status != "lost":
            self.reset()
            self.had_clean = taped and observation.valid
            return False
        if self.had_clean:
            self.candidate = late_possible
        self.had_clean = False
        if not self.candidate:
            return False
        cycles = max(1, round(END_CONFIRM_S / dt))
        self.white_cycles = min(cycles, self.white_cycles + 1)
        return self.white_cycles >= cycles


class LineTracker:
    """Bounded handover; every error is tape-to-travel-left."""
    def __init__(self) -> None:
        self.error_m = 0.0
        self.last_clean_m: float | None = None
        self.age_s = 0.0
        self.source = "odometry"
        self.observation = observe(0)

    def update(self, bits: int, recovery_error_m: float, dt: float,
               allow_hold: bool = True) -> float:
        self.observation = obs = observe(bits)
        if obs.valid:
            self.last_clean_m = obs.error_m
            self.age_s = 0.0
            target = obs.error_m
            self.source = "sensor"
        else:
            self.age_s = round(self.age_s + dt, 9)
            if (allow_hold and self.last_clean_m is not None
                    and self.age_s <= HOLD_S):
                target = self.last_clean_m
                self.source = "hold"
            else:
                target = recovery_error_m
                self.source = "odometry"
        target = max(-ERROR_CAP_M, min(ERROR_CAP_M, target))
        delta = (target - self.error_m) * dt / (FILTER_S + dt)
        bound = ERROR_SLEW_M_S * dt
        self.error_m += max(-bound, min(bound, delta))
        return self.error_m


@dataclass(frozen=True)
class ArraySample:
    black_bits: int
    valid_bits: int
    coverage: tuple[float, ...]
    spots: tuple[tuple[float, float, float] | None, ...]
    positions: tuple[tuple[float, float, float], ...]

    @property
    def indicator_bits(self) -> int:
        return (~self.black_bits) & MASK

    @property
    def gpio_bits(self) -> int:
        return ((~self.black_bits) & MASK) if ACTIVE_LOW else self.black_bits

    def payload(self) -> dict:
        return {"black_bits": self.black_bits,
                "indicator_bits": self.indicator_bits,
                "gpio_bits": self.gpio_bits, "valid_bits": self.valid_bits,
                "illumination_on": True,
                "coverage": [round(v, 4) for v in self.coverage],
                "spots": [list(p) if p is not None else None for p in self.spots],
                "positions": [list(p) for p in self.positions]}


class LineArray:
    def __init__(self) -> None:
        self.bits = 0

    def reset(self) -> None:
        self.bits = 0

    def sample(self, positions, rotations, over_black) -> ArraySample:
        """Project downward optical axes onto the floor, sample a finite
        disk, and expose invalid range/orientation through valid_bits.
        """
        spots, coverage, valid = [], [], 0
        for i, (p, r) in enumerate(zip(positions, rotations)):
            down = (-float(r[2]), -float(r[5]), -float(r[8]))
            distance = -float(p[2]) / down[2] if down[2] < -0.2 else -1.0
            if not MIN_RANGE_M <= distance <= MAX_RANGE_M:
                self.bits &= ~(1 << i)
                spots.append(None)
                coverage.append(0.0)
                continue
            x, y = float(p[0]) + distance * down[0], float(p[1]) + distance * down[1]
            spots.append((x, y, 0.0015))
            valid |= 1 << i
            fraction = sum(over_black(x + ox * FOOTPRINT_RADIUS_M,
                                      y + oy * FOOTPRINT_RADIUS_M)
                           for ox, oy in _DISK) / len(_DISK)
            coverage.append(fraction)
            if fraction >= BLACK_ON:
                self.bits |= 1 << i
            elif fraction <= BLACK_OFF:
                self.bits &= ~(1 << i)
        return ArraySample(self.bits, valid, tuple(coverage), tuple(spots),
                           tuple(tuple(float(v) for v in p) for p in positions))


def scene_payload() -> dict:
    return {"count": N_LINE_SENSORS, "pitch_m": LINE_PITCH,
            "positions": [[x, layout.LINE_BAR_Y / 1000,
                           layout.LINE_FACE_Z / 1000] for x in SENSOR_XS],
            "indicator_z_m": (layout.LINE_FACE_Z + layout.LINE_BAR_H + 1) / 1000,
            "indicator_y_m": (layout.LINE_BAR_Y + 10) / 1000,
            "footprint_radius_m": FOOTPRINT_RADIUS_M,
            "active_low": ACTIVE_LOW,
            "black_on": BLACK_ON, "black_off": BLACK_OFF,
            "range_m": [MIN_RANGE_M, MAX_RANGE_M],
            "calibration": "Optical spot, thresholds and pitch await measurement"}
