"""The race scene frame's track payload -- the viewer's ONLY source of
track truth. Built from the same modules the backend runs (race/track.py
field, race/tasks.py tasks), sent by race/__main__ on the --serve
websocket as part of the scene frame (bot/server.py), so the canvas can
never disagree with the grader and nothing is regenerated by hand.
"""
from . import tasks, track


def _task_entry(t: int) -> dict:
    spec = tasks.task_spec(t)
    return {
        "title": spec["title"],
        "limit_s": spec["limit_s"],
        "laps": spec["laps"],
        "beeps": spec["beeps"],
        "length_m": round(tasks.route_length(t), 3),
    }


def payload() -> dict:
    from bot.line_sensor import scene_payload
    return {
        # SI meters, field frame: X right, Y up, origin at lower-left
        "field": list(track.FIELD),
        "trigger_r": track.TRIGGER_R,
        "tape_half": track.TAPE_HALF,
        "nodes": {k: list(v) for k, v in track.NODES.items()},
        "crossing": list(track.CROSSING),
        "line_array": scene_payload(),
        "tapes": [{"name": seg.name, "center": list(seg.c),
                   "radius": seg.r, "start": seg.a0,
                   "sweep": seg.dir * seg.span,
                   "poly": [[round(x, 4), round(y, 4)]
                            for x, y in track.polyline(seg)]}
                  for seg in track.TAPE],
        # the untaped legs, drawn as ghosts: open white on the real field
        "ghosts": [
            {"name": name, "poly": [[round(x, 4), round(y, 4)] for x, y in poly]}
            for name, poly in track.ghost_polylines()
        ],
        "tasks": {str(t): _task_entry(t) for t in sorted(tasks.TASKS)},
    }
