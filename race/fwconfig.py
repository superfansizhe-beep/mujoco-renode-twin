"""Generate firmware/race/race_fwconfig.h -- the race firmware's C constants.

Same discipline as twin.fwconfig: every number is imported from the
Python single source (race.controller constants, race.track geometry,
race.tasks routes, bot.sensors line-bar layout, bot.* shared stack),
never hand-copied.
Shared balance constants (LQR gains, trim, filter, MPU scaling, motor
two-point line) are NOT duplicated here -- the header includes
twin_fwconfig.h, the same generated file the balance firmware uses.

The route GEOMETRY is baked per task at generation time: each segment
leaves as a travel-oriented record (straight: start point + unit
tangent + heading; arc: center/radius/start-angle/sweep-direction),
so the C project()/heading_at()/curvature_at() mirror race.track's
math with orientation already folded in -- including the Arc.project
clamp-to-nearer-end semantics the bring-up fought for.

Run:  python -m race.fwconfig            (write the header)
      python -m race.fwconfig --check    (exit 1 when stale)
"""
import argparse
import math
import os
import sys

DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(__file__), "..", "firmware", "race", "race_fwconfig.h")


def _seg_record(o) -> tuple[str, list[float]]:
    """Oriented segment -> baked travel-direction parameter vector."""
    from . import track
    if isinstance(o.seg, track.Straight):
        p0, p1 = o.point(0.0), o.point(o.length)
        dx, dy = p1[0] - p0[0], p1[1] - p0[1]
        length = math.hypot(dx, dy)
        return ("straight",
                [p0[0], p0[1], dx / length, dy / length, o.heading_at(0.0)])
    a = o.seg
    a0 = a.a0 + a.dir * a.span if o.reverse else a.a0
    dr = -a.dir if o.reverse else a.dir
    return ("arc", [a.c[0], a.c[1], a.r, a0, dr, a.span])


def render() -> str:
    from . import controller as ctl, tasks, track
    from bot.loop import COUPLING_S
    from bot.sensors import LINE_PITCH, N_LINE_SENSORS

    def f(v: float) -> str:
        s = f"{v:.9g}"
        if not any(c in s for c in ".eE"):   # C needs a decimal point to be a float constant
            s += ".0"
        return s + "f"

    # route tables: task -> baked segment records
    lines = []
    for task in sorted(tasks.TASKS):
        route = tasks.task_route(task)
        lines.append(f"/* task {task}: {tasks.TASKS[task].title} */")
        lines.append(f"static const race_seg_t RACE_ROUTE_T{task}"
                     f"[{len(route)}] = {{")
        for o in route:
            kind, p = _seg_record(o)
            vals = ", ".join(f(v) for v in p)
            if kind == "straight":
                lines.append(f"    {{0, {int(o.taped)}, {f(o.length)}, "
                             f"{{.s={{{vals}}}}}}},   /* {o.name} */")
            else:
                lines.append(f"    {{1, {int(o.taped)}, {f(o.length)}, "
                             f"{{.a={{{vals}}}}}}},   /* {o.name} */")
        lines.append("};")
        lines.append("")
    routes_c = "\n".join(lines[:-1])       # drop the trailing blank

    return f"""/* Race firmware control constants -- GENERATED by `python -m race.fwconfig`, no hand edits.
 * Single sources: race.controller (all tuning constants), race.tasks (exam
 * route table, orientation baked into the parameters), race.mailbox (line-bar
 * layout); shared balance constants (LQR gains/trim/filter/MPU scaling/motor
 * two-point line) are not duplicated here -- include twin_fwconfig.h directly
 * (generated by twin.fwconfig, same source as the balance firmware).
 * Regenerate after changing any Python constant; the tests catch stale headers.
 * The C side builds as float32; the delta vs Python float64 is absorbed by the
 * A/B cross-check tolerance.
 */
#ifndef RACE_FWCONFIG_H
#define RACE_FWCONFIG_H

#include "twin_fwconfig.h"   /* TWIN_DT_S/ALPHA/K_LQR/THETA_REF/DUTY_CAP/
                                COUNTS_PER_M/MPU scaling/motor lines -- shared */

/* ---- task timing / stopping ---- */
#define RACE_ARM_S          {f(ctl.ARM_S)}   /* stand steady after power-on, then go */
#define RACE_A_MAX          {f(ctl.A_MAX)}   /* m/s^2 plan ramp */
#define RACE_A_MAX_KINK     {f(ctl.A_MAX_KINK)}   /* slow ramp after large kinks */
#define RACE_A_MAX_BRAKE    {f(ctl.A_MAX_BRAKE)}
#define RACE_REF_LEAK       {f(ctl.REF_LEAK)}   /* one-sided reference governor, m/s */
#define RACE_REF_LEAK_BRAKE {f(ctl.REF_LEAK_BRAKE)}   /* brake-side follower, m/s */
#define RACE_STOP_V         {f(ctl.STOP_V)}
#define RACE_STOP_V_LPF_HZ  {f(ctl.STOP_V_LPF_HZ)}   /* stop estimate only */
#define RACE_STOP_W         {f(ctl.STOP_W)}
#define RACE_STOP_S         {f(ctl.STOP_S)}
#define RACE_BEEP_MS        {ctl.BEEP_MS}
#define RACE_LED_MS         {ctl.LED_MS}
#define RACE_MS_PER_CYCLE   {int(round(COUPLING_S * 1000))}   /* buzzer countdown step */

/* ---- speed table (travel axis) ---- */
#define RACE_V_STRAIGHT     {f(ctl.SPEED_BASE['straight'])}
#define RACE_V_R40          {f(ctl.SPEED_BASE['r40'])}
#define RACE_V_NODE         {f(ctl.SPEED_BASE['node'])}
#define RACE_VT_STRAIGHT    {f(ctl.SPEED_TURBO['straight'])}
#define RACE_VT_R40         {f(ctl.SPEED_TURBO['r40'])}
#define RACE_VT_NODE        {f(ctl.SPEED_TURBO['node'])}

/* ---- line tracking / recovery ---- */
#define RACE_KP_LAT         {f(ctl.KP_LAT)}
#define RACE_KD_RATE        {f(ctl.KD_RATE)}
#define RACE_KP_HEAD        {f(ctl.KP_HEAD)}
#define RACE_LOST_S         {f(ctl.LOST_S)}
#define RACE_SWEEP_AFTER    {f(ctl.SWEEP_AFTER)}
#define RACE_SWEEP_RAD      {f(ctl.SWEEP_RAD)}
#define RACE_SWEEP_T        {f(ctl.SWEEP_T)}
#define RACE_PARK_LOST_S    {f(ctl.PARK_LOST_S)}
#define RACE_E_SLOW         {f(ctl.E_SLOW)}   /* lateral error that slows the cruise */
#define RACE_E_SLOW_V       {f(ctl.E_SLOW_V)}   /* cruise cap while off-center */

/* ---- odometry ---- */
#define RACE_ODO_K          {f(ctl.ODO_K)}
#define RACE_SCRUB_K        {f(ctl.SCRUB_K)}
#define RACE_ENC_SCALE      {f(ctl.ENC_SCALE)}
#define RACE_TRIGGER_R      {f(track.TRIGGER_R)}   /* node trigger radius 5 cm */

/* ---- node trigger / kink ---- */
#define RACE_FINAL_LEAD     {f(ctl.FINAL_LEAD)}
#define RACE_FINAL_LEAD_SHORT {f(ctl.FINAL_LEAD_SHORT)}
#define RACE_BLOB_MIN       {ctl.BLOB_MIN}
#define RACE_BLOB_S         {f(ctl.BLOB_S)}
#define RACE_ALIGN_MAX_S    {f(ctl.ALIGN_MAX_S)}
#define RACE_K_ALIGN        {f(ctl.K_ALIGN)}
#define RACE_KINK_STOP      {f(ctl.KINK_STOP)}
#define RACE_KINK_GO        {f(ctl.KINK_GO)}

/* ---- steering servo ---- */
#define RACE_W_CMD_CAP      {f(ctl.W_CMD_CAP)}
#define RACE_W_LPF_HZ       {f(ctl.W_LPF_HZ)}
#define RACE_K_YAW          {f(ctl.K_YAW)}
#define RACE_KI_YAW         {f(ctl.KI_YAW)}
#define RACE_TAU_WI_CAP     {f(ctl.TAU_WI_CAP)}
#define RACE_TAU_D_CAP      {f(ctl.TAU_D_CAP)}
#define RACE_DUTY_D_SLEW    {ctl.DUTY_D_SLEW}   /* permille/cycle @200Hz */

/* ---- line-tracking bar (single source: bot.sensors) ---- */
#define RACE_N_LINE_SENSORS {N_LINE_SENSORS}
#define RACE_LINE_PITCH     {f(LINE_PITCH)}

/* ---- route geometry tables: baked by race.tasks.task_route(), orientation
 *      folded into the parameters ----
 * straight: travel-direction p0/unit tangent/heading (s=dot(p-p0,u) clamped
 *       to [0,len], lat=cross; isomorphic with track.Straight.project).
 * arc: travel-direction center/radius/start angle/sweep dir(±1)/span;
 *     s=r*wrap(theta-a0)*dir (out of the sweep, clamp to the nearer end by
 *     angle distance -- on a half-circle this decides whether 10 cm before
 *     the node reads s=0 or s=len, the bug fixed during bring-up),
 *     lat=dir*(r-r_pt), heading=theta+dir*pi/2.
 * taped: the field's only markings are the two arcs (track.TAPE) -- the
 *     firmware's blind-leg gating keys on this bit, straight records
 *     bake 0 and both arcs bake 1.
 */
typedef struct {{
    uint8_t is_arc;    /* 0 = straight, 1 = arc */
    uint8_t taped;     /* 1 = carries guide tape (race.track.TAPE) */
    float len;
    union {{
        struct {{ float p0x, p0y, ux, uy, psi; }} s;
        struct {{ float cx, cy, r, a0, dir, span; }} a;
    }} g;
}} race_seg_t;

{routes_c}

#endif /* RACE_FWCONFIG_H */
"""


def check(path: str = DEFAULT_OUTPUT) -> tuple[bool, str]:
    """True when the on-disk header matches a fresh render."""
    if not os.path.isfile(path):
        return False, f"{path} missing"
    with open(path, encoding="utf-8") as fp:
        current = fp.read()
    if current == render():
        from bot.line_sensor import firmware_config
        line_path = os.path.join(os.path.dirname(DEFAULT_OUTPUT), "..", "line_config.h")
        if not os.path.isfile(line_path):
            return False, f"{line_path} missing -- rerun python -m race.fwconfig"
        with open(line_path, encoding="utf-8") as fp:
            if fp.read() != firmware_config():
                return False, f"{line_path} stale -- rerun python -m race.fwconfig"
        return True, ""
    return False, (f"{path} is stale -- rerun `python -m race.fwconfig` "
                   f"(race-side constants changed)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="race.fwconfig")
    ap.add_argument("--output", default=DEFAULT_OUTPUT)
    ap.add_argument("--check", action="store_true",
                    help="verify freshness instead of writing")
    args = ap.parse_args(argv)
    if args.check:
        ok, msg = check(args.output)
        if not ok:
            print(f"STALE: {msg}", file=sys.stderr)
            return 1
        print("race fwconfig header in sync")
        return 0
    with open(args.output, "w", encoding="utf-8") as fp:
        fp.write(render())
    from bot.line_sensor import firmware_config
    line_path = os.path.join(os.path.dirname(DEFAULT_OUTPUT), "..", "line_config.h")
    with open(line_path, "w", encoding="utf-8") as fp:
        fp.write(firmware_config())
    print(f"wrote {os.path.normpath(args.output)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
