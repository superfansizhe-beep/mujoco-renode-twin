"""Generate firmware/twin/twin_fwconfig.h -- the C-side control constants.

Single source of truth: every number is imported from the platform's
Python side (bot.backend / bot.sensors / bot.motors / bot.loop /
cad_modeling.layout), never hand-copied. Hand-editing the header is
forbidden -- the consistency test fails on any drift and says so.

Run:  python -m twin.fwconfig           (write the header)
      python -m twin.fwconfig --check   (exit 1 with a hint when stale)
"""
import argparse
import os
import sys

DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(__file__), "..", "firmware", "twin", "twin_fwconfig.h")


def render() -> str:
    from bot import motors, sensors
    from bot.backend import BalanceController
    from bot.loop import COUPLING_S
    from cad_modeling.layout import WHEEL_R

    bc = BalanceController(dt=COUPLING_S,
                           v_batt=motors.BATTERY_NOMINAL["3s"])

    def f(v: float) -> str:
        s = f"{v:.9g}"
        if not any(c in s for c in ".eE"):   # C needs a decimal point to be a float constant
            s += ".0"
        return s + "f"

    k = bc.K_LQR
    return f"""/* Balance firmware control constants -- GENERATED by `python -m twin.fwconfig`, hand edits forbidden.
 * Single source: bot.backend.BalanceController (gains/filter/clamps/trim),
 * bot.sensors (MPU6050 scaling + COUNTS_PER_M), bot.motors (motor
 * two-point line), bot.loop.COUPLING_S (coupling rate),
 * cad_modeling.layout.WHEEL_R.
 * Must regenerate after any mass-table/gain recompute; tests catch a stale header.
 * The C side compiles as float32; the delta vs Python float64 is absorbed by
 * the A/B comparison tolerance.
 */
#ifndef TWIN_FWCONFIG_H
#define TWIN_FWCONFIG_H

#define TWIN_DT_S            {f(COUPLING_S)}   /* coupling period = IMU ODR 200 Hz */
#define TWIN_ALPHA_F         {f(bc.ALPHA)}   /* complementary filter weight */
#define TWIN_THETA_REF_RAD   {f(bc.theta_ref)}   /* trim: tilt with CoM over the wheel-contact line */
#define TWIN_K_LQR_0         {f(k[0])}   /* [y, ydot, theta-theta_ref, thetadot] */
#define TWIN_K_LQR_1         {f(k[1])}
#define TWIN_K_LQR_2         {f(k[2])}
#define TWIN_K_LQR_3         {f(k[3])}
#define TWIN_DUTY_CAP_PM     {bc.DUTY_CAP}   /* permille, traction cap */
#define TWIN_COUNTS_PER_REV  {f(float(sensors.COUNTS_PER_REV))}   /* 11PPR x4 x30 */
#define TWIN_COUNTS_PER_M    {f(sensors.COUNTS_PER_M)}
#define TWIN_WHEEL_R_M       {f(WHEEL_R / 1000.0)}
#define TWIN_ACCEL_LSB_PER_G {f(sensors.ACCEL_LSB_PER_G)}   /* MPU6050 +-2g */
#define TWIN_GYRO_LSB_PER_DPS {f(sensors.GYRO_LSB_PER_DPS)}   /* +-250dps */
#define TWIN_G_MPS2          {f(sensors.G_MPS2)}
#define TWIN_STALL_NM        {f(motors.STALL_NM)}   /* 12V stall, SHEET */
#define TWIN_V_NOM           {f(motors.V_NOM)}

#endif /* TWIN_FWCONFIG_H */
"""


def check(path: str = DEFAULT_OUTPUT) -> tuple[bool, str]:
    """True when the on-disk header matches a fresh render."""
    if not os.path.isfile(path):
        return False, f"{path} missing"
    with open(path, encoding="utf-8") as fp:
        current = fp.read()
    if current == render():
        return True, ""
    return False, (f"{path} is stale -- rerun `python -m twin.fwconfig` "
                   f"(twin-side constants changed)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="twin.fwconfig")
    ap.add_argument("--output", default=DEFAULT_OUTPUT)
    ap.add_argument("--check", action="store_true",
                    help="verify freshness instead of writing")
    args = ap.parse_args(argv)
    if args.check:
        ok, msg = check(args.output)
        if not ok:
            print(f"STALE: {msg}", file=sys.stderr)
            return 1
        print("fwconfig header in sync")
        return 0
    with open(args.output, "w", encoding="utf-8") as fp:
        fp.write(render())
    print(f"wrote {os.path.normpath(args.output)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
